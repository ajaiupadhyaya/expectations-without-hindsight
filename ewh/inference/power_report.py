"""Write docs/power.md: template-inference size table (D8) and Arm A MDE curves (D13).

`python -m ewh.inference.power_report [reps_size]`. Power-namespace seeds only.
"""

from __future__ import annotations

import json
import sys
import warnings

import numpy as np

from ewh.inference import power as pw
from ewh.provenance.archive import REPO_ROOT

OUT = REPO_ROOT / "docs" / "power.md"
DATA = REPO_ROOT / "data" / "processed" / "power.json"
THETAS = (-0.4, 0.0)
KAPPAS = (0.5, 1.0, 2.0, 3.0)
KS = (8, 16)
TAUS = (0.0, 0.025, 0.05, 0.1)
BASE_PATHS = 40  # per model x template x rho in the variance runs
UNITS_PER_MODEL_PER_PATH = 2 * pw.N_PAR * 5  # templates x pooled rho cells


def variance_constants(reps: int = 30) -> list[dict]:
    rows = []
    for th in THETAS:
        for sh in KAPPAS:
            for k in KS:
                des = pw.Design(models=1, paths=BASE_PATHS, k=k, theta=th, tau=0.0, kappa=sh)
                r = pw.se_per_unit(des, f"var|{th}|{sh}|{k}", reps)
                U = BASE_PATHS * UNITS_PER_MODEL_PER_PATH
                rows.append(
                    dict(
                        theta=th,
                        kappa=sh,
                        k=k,
                        c_iv=r["iv_sd"] ** 2 * U,
                        c_gap=r["gap_sd"] ** 2 * U,
                        iv_mean=r["iv_mean"],
                        naive_mean=r["naive_mean"],
                    )
                )
    return rows


def pooling_rows(reps: int = 30) -> list[dict]:
    rows = []
    for th in (-0.4, 0.0, 0.3):
        for ka in (0.5, 1.0, 2.0):
            for k in (16, 32, 64):
                des = pw.Design(models=1, paths=BASE_PATHS, k=k, theta=th, kappa=ka)
                for name, v in pw.pooling_grid(des, f"{th}|{ka}|{k}", reps).items():
                    rows.append(dict(theta=th, kappa=ka, k=k, pooling=name, **v))
    return rows


def mde_b(c: float, units: int, tau: float, n_par: int = pw.N_PAR) -> float:
    return pw.mde(np.sqrt(tau**2 / n_par + c / units), df=n_par - 1)


def main(argv):
    warnings.simplefilter("ignore")
    reps = int(argv[0]) if argv else 500
    size = {
        tau: pw.size_table(
            pw.Design(models=1, paths=40, k=16, theta=0.0, tau=tau, kappa=1.0), reps, f"size|{tau}"
        )
        for tau in (0.0, 0.05, 0.1)
    }
    var = variance_constants()
    DATA.parent.mkdir(parents=True, exist_ok=True)
    DATA.write_text(
        json.dumps(
            dict(size={str(k): v for k, v in size.items()}, var=var), indent=2, default=float
        )
    )
    L = [
        "# Power and size (Phase 3.7)",
        "",
        "Generated by `python -m ewh.inference.power_report`; power-namespace seeds; do not edit.",
        "",
        "## Template inference (plan D8): rejection rate at 5% under the null",
        "",
        f"{reps} replications per row (Monte Carlo s.e. about "
        f"{100 * np.sqrt(0.05 * 0.95 / reps):.1f} points). One model, 40 paths per template x "
        "rho, K = 16, noise s.d. = innovation s.d. (kappa = 1). "
        "tau = s.d. of the noise-free coefficient across "
        "paraphrases (template as a random factor).",
        "",
        f"| tau | (a) cluster by path | (b) paraphrase t-test ({pw.N_PAR - 1} df) "
        "| (c) wild bootstrap by paraphrase |",
        "|---|---|---|---|",
    ]
    for tau, r in size.items():
        L.append(
            f"| {tau:.2f} | {r['a_path']:.3f} | {r['b_paraphrase_t']:.3f} | "
            f"{r['c_wild_paraphrase']:.3f} |"
        )
    L += [
        "",
        "Only (b) holds its size at every tau, so it is the proposed primary template "
        "inference; (a) and (c) are robustness rows.",
        "",
        "## Sampling variance per unit",
        "",
        "c = Var(pooled estimate) x units, from 30 replications of one model with 40 paths per "
        f"template x rho ({BASE_PATHS * UNITS_PER_MODEL_PER_PATH:,} units over the five pooled rho "
        "cells), tau = 0.",
        "",
        "| true b | kappa (noise s.d. / innovation s.d.) | K | c (split IV) | c (H1 gap) "
        "| mean IV | mean one-draw |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in var:
        L.append(
            f"| {r['theta']:.1f} | {r['kappa']:.1f} | {r['k']} | {r['c_iv']:.1f} | "
            f"{r['c_gap']:.1f} | {r['iv_mean']:.3f} | {r['naive_mean']:.3f} |"
        )
    pool = pooling_rows()
    DATA.write_text(
        json.dumps(
            dict(size={str(k): v for k, v in size.items()}, var=var, pooling=pool),
            indent=2,
            default=float,
        )
    )
    L += [
        "",
        "## Pooling across persistence cells and the number of draws",
        "",
        f"One model, 40 paths per template x rho ({BASE_PATHS * UNITS_PER_MODEL_PER_PATH:,} units "
        "over five cells), 30 replications. "
        "rsd = robust s.d. (1.4826 x MAD) of the pooled split IV, because the ratio's variance "
        "need not exist when a cell's instrument is weak. weak = share of replications whose "
        "weakest pooled cell has first-stage t^2 < 10.",
        "",
        "| true b | kappa | K | equal 0.2-1: rsd (weak) | equal 0.4-1: rsd (weak) | "
        "rho^2 weights 0.2-1: rsd (weak) |",
        "|---|---|---|---|---|---|",
    ]
    by = {}
    for r in pool:
        by.setdefault((r["theta"], r["kappa"], r["k"]), {})[r["pooling"]] = r
    for (th, ka, k), v in sorted(by.items()):
        cells = [
            f"{v[p]['iv_rsd']:.3f} ({v[p]['weak_share']:.2f})"
            for p in ("equal_02_1", "equal_04_1", "rho2_02_1")
        ]
        L.append(f"| {th:.1f} | {ka:.1f} | {k} | " + " | ".join(cells) + " |")
    L += [
        "",
        "**Reading.** Equal weights over rho 0.2-1 (the draft plan) are the least precise and "
        "inherit a weak instrument from the rho = 0.2 cell once the per-draw noise is about the "
        "size of an innovation or more: a near-rational forecaster revises very little at low "
        "persistence. Dropping rho = 0.2 from the pooled estimand, or fixed weights proportional "
        "to rho^2, removes the problem; K = 32 helps at high noise. Proposed for the PAP: equal "
        "weights over rho in {0.4, 0.6, 0.8, 1} as primary, rho^2 weights as robustness, rho = 0 "
        "and 0.2 reported per cell with Fieller sets; K = 32.",
        "",
        "## MDE of the pooled corrected coefficient (H2), primary pooling",
        "",
        f"Method (b) across the {pw.N_PAR} paraphrases: "
        f"MDE = (t,0.975 + t,0.80; {pw.N_PAR - 1} df) x "
        f"sqrt(tau^2/{pw.N_PAR} + rsd1^2/M), "
        "rsd1 = per-model robust s.d. at "
        f"{BASE_PATHS * UNITS_PER_MODEL_PER_PATH:,} units (40 paths per template x rho) for equal "
        "weights over rho 0.4-1, K = 32, worst case over true b in the grid.",
        "",
        "| kappa | models M | paths per cell | " + " | ".join(f"tau = {t}" for t in TAUS) + " |",
        "|---|---|---|" + "---|" * len(TAUS),
    ]
    for ka in (0.5, 1.0, 2.0):
        r1 = max(v["equal_04_1"]["iv_rsd"] for (th, kk, k), v in by.items() if kk == ka and k == 32)
        for M in (6, 26):
            for paths in (40, 80, 160):
                s2 = r1**2 * BASE_PATHS / paths / M
                mdes = [
                    f"{pw.mde(np.sqrt(t**2 / pw.N_PAR + s2), df=pw.N_PAR - 1):.3f}" for t in TAUS
                ]
                L.append(f"| {ka:.1f} | {M} | {paths} | " + " | ".join(mdes) + " |")
    floor = {t: pw.mde(t / np.sqrt(pw.N_PAR), df=pw.N_PAR - 1) for t in TAUS}
    L += [
        "",
        "Floor from paraphrase heterogeneity alone: "
        + ", ".join(f"tau {t}: {v:.3f}" for t, v in floor.items())
        + ".",
        "",
        f"**Reading.** With {pw.N_PAR} paraphrases the floor from paraphrase heterogeneity is "
        f"{floor[0.025]:.3f} at tau = 0.025, {floor[0.05]:.3f} at tau = 0.05 and {floor[0.1]:.3f} "
        "at tau = 0.1; more paths shrink only the sampling term. The CPU pilot could not "
        "estimate tau (docs/pilot_log.md, Pilot 1).",
        "",
    ]
    OUT.write_text("\n".join(L))
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
