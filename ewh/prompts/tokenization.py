"""Tokenization audit (plan Task 3.1): how each tokenizer splits the numbers our prompts show.

Writes docs/tokenization.md. Tokenizer files only are downloaded (no weights), pinned to the
revisions in configs/generation.yaml. `python -m ewh.prompts.tokenization`
"""

from __future__ import annotations

import sys
from collections import Counter

import tiktoken
import yaml

from ewh.provenance.archive import REPO_ROOT

CFG = yaml.safe_load((REPO_ROOT / "configs" / "generation.yaml").read_text())
HF_TOKENIZERS = ["Qwen2.5-0.5B-Instruct", "Qwen2-0.5B-Instruct", "Llama-3.2-1B-Instruct", "gpt2"]
INTS = list(range(-400, 401)) + list(range(401, 1601, 7))
DECS = [round(x / 10, 1) for x in range(-300, 301)]
OUT = REPO_ROOT / "docs" / "tokenization.md"


def encoders():
    yield "ChronoGPT (tiktoken gpt2)", lambda s: tiktoken.get_encoding("gpt2").encode(s)
    from transformers import AutoTokenizer

    for name in HF_TOKENIZERS:
        m = CFG["models"][name]
        try:
            tok = AutoTokenizer.from_pretrained(m["repo"], revision=m["revision"])
        except Exception as e:  # gated repo without access, offline, ...
            yield f"{name} (unavailable: {type(e).__name__})", None
            continue
        yield name, lambda s, tok=tok: tok.encode(s, add_special_tokens=False)


def audit(enc) -> dict:
    """Token counts of numbers as they appear after ', ' (comma format) and ': ' (indexed)."""
    out = {}
    for label, nums, fmt in (("integers", INTS, "{:d}"), ("one decimal", DECS, "{:.1f}")):
        counts = Counter()
        neg_split = 0
        for v in nums:
            s = fmt.format(v)
            base = len(enc("x,"))
            n = len(enc(f"x, {s}")) - base
            counts[n] += 1
            if v < 0 and len(enc(f" {s}")) > len(enc(f" {s[1:]}")):
                neg_split += 1
        out[label] = (dict(sorted(counts.items())), neg_split, sum(v < 0 for v in nums))
    return out


def main() -> int:
    lines = [
        "# Tokenization audit",
        "",
        "Generated by `python -m ewh.prompts.tokenization`. How many tokens each number takes",
        "when it follows `, ` in a prompt, for the ranges our prompts use: integers −400…1,600",
        "(Arm A paths, and 3x + 500 in the scale gate) and one-decimal values −30.0…30.0 (Arm B).",
        "",
        "| Tokenizer | Numbers | Tokens per number: count of values | Negatives whose minus sign "
        "adds a token |",
        "|---|---|---|---|",
    ]
    for name, enc in encoders():
        if enc is None:
            lines.append(f"| {name} | | | |")
            continue
        for label, (counts, neg, nneg) in audit(enc).items():
            dist = ", ".join(f"{k}: {v}" for k, v in counts.items())
            lines.append(f"| {name} | {label} | {dist} | {neg} of {nneg} |")
    lines += [
        "",
        "Reading: GPT-2 BPE (ChronoGPT) merges digit runs, so numbers of similar magnitude take",
        "one or two tokens and a minus sign is almost always a separate token; Qwen tokenizes",
        "digit by digit, so token counts rise with the number of digits. Any effect of",
        "tokenization on forecasts is common to all ChronoGPT vintages (one tokenizer) and is",
        "part of what the capability ladder compares descriptively. A tokenizer marked",
        "unavailable could not be downloaded (gated access not yet granted).",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
