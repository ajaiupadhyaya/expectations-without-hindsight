"""CPU dry run (plan Task 3.6): the whole Arm A pipeline on planted forecasters, plus the gpt2
stand-in through the transformers backend. Dry-run seeds only; no ChronoGPT model is used.

`python -m ewh.dryrun` writes data/dryrun/ (draws, ledger, results) and paper/generated/dryrun.tex.
"""

from __future__ import annotations

import json
import sys

import numpy as np
import pandas as pd

from ewh.analysis import arm_a
from ewh.capability import gate
from ewh.models.backend import PlantedBackend
from ewh.models.ledger import Ledger
from ewh.models.runner import GenerationConfig, read_draws, run_shards
from ewh.prompts import tables as tb
from ewh.provenance.archive import REPO_ROOT
from ewh.sim import ar1, planted

OUT = REPO_ROOT / "data" / "dryrun"
TEX = REPO_ROOT / "paper" / "generated" / "dryrun.tex"
SEED = ar1.seeds()["dryrun"]
K = 16
THETAS = (-0.3, 0.3)
NOISE_SD = 15.0


def planted_run(theta: float, table: pd.DataFrame) -> dict:
    cfg = GenerationConfig(
        k=K, temperature=1.0, max_new_tokens=12, master_seed=SEED, shard_size=2000
    )
    be = PlantedBackend(table, theta=theta, noise_sd=NOISE_SD, name=f"planted{theta:+.1f}")
    run_shards(be, table, OUT / "draws", cfg, Ledger(OUT / "ledger.jsonl"), batch_size=500)
    draws = read_draws(OUT / "draws", be.name)
    res = arm_a.analyse(table, draws, K)
    pred = np.mean([planted.naive_limit(r, theta, NOISE_SD, NOISE_SD) for r in arm_a.POOLED_RHOS])
    iv, nv = res["pooled"]["split_iv"], res["pooled"]["naive_stacked"]
    return dict(
        theta=theta,
        split_iv=iv.b,
        split_iv_se=iv.se,
        naive=nv.b,
        naive_se=nv.se,
        naive_predicted=pred,
        h1=res["H1"]["b"],
        h1_se=res["H1"]["se"],
        h2_ls=res["H2_LS"]["b"],
        h3=res["H3"]["b"],
        noise_share=res["noise_share_t"],
        recovered=abs(iv.b - theta) < 3 * iv.se and abs(nv.b - pred) < 3 * nv.se,
    )


def gpt2_run(n_gate: int = 6) -> dict:
    """gpt2 (pinned revision) on a small gate table: exercises the transformers backend and the
    parser on real model text, and shows a weak model failing the gate."""
    import torch
    import yaml
    from transformers import AutoModelForCausalLM, AutoTokenizer

    from ewh.models.backend import HFBackend

    m = yaml.safe_load((REPO_ROOT / "configs" / "generation.yaml").read_text())["models"]["gpt2"]
    tok = AutoTokenizer.from_pretrained(m["repo"], revision=m["revision"])
    model = AutoModelForCausalLM.from_pretrained(
        m["repo"], revision=m["revision"], torch_dtype=torch.float32
    )
    be = HFBackend(model.eval(), tok, m["revision"], "gpt2", chat=False)
    gt = tb.build_gate("dryrun", ["gpt2"], n_gate)
    cfg = GenerationConfig(
        k=8, temperature=1.0, max_new_tokens=12, master_seed=SEED, shard_size=500
    )
    run_shards(be, gt, OUT / "draws", cfg, Ledger(OUT / "ledger.jsonl"), batch_size=8)
    d = read_draws(OUT / "draws", "gpt2")
    wide = (
        d[d.draw >= 0]
        .pivot_table(index="prompt_id", columns="draw", values="parsed", dropna=False)
        .reindex(gt.prompt_id)
    )
    r = gate.gate_stats(gt, wide.to_numpy(float))
    examples = d[d.draw >= 0].raw_text.head(5).tolist()
    return dict(gate_pass=r["pass"], parse_rate=r["parse_rate"], examples=examples)


def write_tex(results: list[dict], g: dict | None) -> None:
    def mac(name, v):
        return f"\\newcommand{{\\{name}}}{{{v}}}"

    lines = ["% Generated by python -m ewh.dryrun. Do not edit."]
    for r in results:
        tag = "Neg" if r["theta"] < 0 else "Pos"
        lines += [
            mac(f"dryTheta{tag}", f"{r['theta']:.2f}"),
            mac(f"dryIV{tag}", f"{r['split_iv']:.3f}"),
            mac(f"dryIVse{tag}", f"{r['split_iv_se']:.3f}"),
            mac(f"dryNaive{tag}", f"{r['naive']:.3f}"),
            mac(f"dryNaivePred{tag}", f"{r['naive_predicted']:.3f}"),
        ]
    if g:
        lines.append(mac("dryGptParse", f"{100 * g['parse_rate']:.0f}"))
        lines.append(mac("dryGptGate", "passes" if g["gate_pass"] else "fails"))
    TEX.parent.mkdir(parents=True, exist_ok=True)
    TEX.write_text("\n".join(lines) + "\n")


def main(argv: list[str]) -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    table = tb.build_arm_a("dryrun", ["planted"], 40)
    results = [planted_run(th, table) for th in THETAS]
    g = None if "--no-gpt2" in argv else gpt2_run()
    (OUT / "results.json").write_text(
        json.dumps(dict(planted=results, gpt2=g), indent=2, default=float)
    )
    write_tex(results, g)
    for r in results:
        print({k: (round(v, 3) if isinstance(v, float) else v) for k, v in r.items()})
    if g:
        print("gpt2:", {k: v for k, v in g.items()})
    ok = all(r["recovered"] for r in results) and (g is None or not g["gate_pass"])
    print("DRY RUN", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
